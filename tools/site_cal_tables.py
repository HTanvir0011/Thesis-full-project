"""LaTeX tables of the SAP_v5 site-calibration results (exploratory; protocol/SAP_v5.md), written from the saved result files.

python tools/site_cal_tables.py  -> paper/tables/site_cal_{fidelity,tests,ribcxr}.tex (then python tools/pack_overleaf.py)
Reads results/site_cal/{heldout_stats,audit_stats}.json, results/site_cal/rib_*_cal.csv, results/final/rib/{ours,qure}.csv and the BS-LDM
held-out rows of results/final/szch/bsldm.csv. No number is typed by hand.
"""
import csv
import json
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[1]
R, T = ROOT / "results", ROOT / "paper" / "tables"  # generated tables live in paper/tables; tools/pack_overleaf.py copies them to submission/
NAMES = [("identity", "identity (no suppression)"), ("ours", "ours (ConvNeXt-V2-T, $K=3$)"), ("notwin", "no-twin control"),
         ("clia_v1", "v1 model"), ("qure", "reference model")]


def f(v, d):
    return "--" if v is None else (f"{v:.{d}f}".replace("-", "$-$") if v < 0 else f"{v:.{d}f}")


def fidelity(h):
    held = set(json.loads((ROOT / "protocol" / "freeze_v2.json").read_text())["szch_heldout"])
    bs = [r for r in csv.DictReader(open(R / "final" / "szch" / "bsldm.csv")) if r["image"] in held]
    assert len(bs) == h["n_images"] == 51
    rows = []
    for key, label in NAMES:
        a, c = h["means"][key], h["means"][key + "_cal"]
        rows.append([label] + [f(x[k], d) for k, d in (("psnr_cal_bone", 2), ("psnr_cal", 2), ("ssim_cal", 3), ("lpips_cal", 3))
                               for x in (a, c)])
    bm = {k: mean(float(r[k]) for r in bs) for k in ("psnr_cal_bone", "psnr_cal", "ssim_cal")}
    rows.append(["BS-LDM (trained on this site's pairs)", f(bm["psnr_cal_bone"], 2), "--", f(bm["psnr_cal"], 2), "--",
                 f(bm["ssim_cal"], 3), "--", "--", "--"])
    head = ("method & \\multicolumn{2}{c}{bone-region PSNR$_{cal}$} & \\multicolumn{2}{c}{PSNR$_{cal}$} & \\multicolumn{2}{c}{SSIM$_{cal}$} "
            "& \\multicolumn{2}{c}{LPIPS} \\\\\n\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\n"
            " & as is & site-cal. & as is & site-cal. & as is & site-cal. & as is & site-cal. \\\\")
    return ("% SAP_v5 D1 (exploratory): 51 held-out SZCH pairs, every method as is and site-calibrated (correction fitted on the 24\n"
            "% development pairs). Generated by tools/site_cal_tables.py.\n\\begin{tabular}{lcccccccc}\n\\toprule\n" + head +
            "\n\\midrule\n" + "\n".join(" & ".join(r) + " \\\\" for r in rows) + "\n\\bottomrule\n\\end{tabular}\n")


def rib_means(p):
    rows = list(csv.DictReader(open(p)))
    assert len(rows) == 245, p
    return [mean(float(r[k]) for r in rows) for k in ("r_rib", "r_non", "selectivity", "auc")]


def tests(h, a):
    yes = lambda b: "yes" if b else "no"  # noqa: E731
    rows = [["H16: bone-region PSNR$_{cal}$, site-cal. $-$ as is (ours)", f(h["H16_psnr_cal_bone"]["mean"], 2) + " dB",
             f(h["H16_psnr_cal_bone"]["lower"], 2) + " dB", "bound $>0$", yes(h["H16_psnr_cal_bone"]["non_inferior"])],
            ["H16b: PSNR$_{cal}$, site-cal. $-$ as is (ours)", f(h["H16_psnr_cal"]["mean"], 2) + " dB",
             f(h["H16_psnr_cal"]["lower"], 2) + " dB", "bound $>0$", yes(h["H16_psnr_cal"]["non_inferior"])],
            ["H17: bone-region PSNR$_{cal}$, ours $-$ reference (both site-cal.)", f(h["H17_psnr_cal_bone"]["mean"], 2) + " dB",
             f(h["H17_psnr_cal_bone"]["lower"], 2) + " dB", "bound $>-0.5$ dB", yes(h["H17_psnr_cal_bone"]["non_inferior"])]]
    for key, label, crit in (("H18_ours_cal_minus_qure_cal", "H18: absorption $A$, ours $-$ reference (both site-cal.)", "upper $<0$"),
                             ("ours_cal_minus_ours", "absorption $A$ of ours, site-cal. $-$ as is", "descriptive"),
                             ("qure_cal_minus_qure", "absorption $A$ of the reference, site-cal. $-$ as is", "descriptive")):
        d = a[key]
        rows.append([label, f(d["mean"], 3), f"[{f(d['lo'], 3)}, {f(d['hi'], 3)}]", crit,
                     yes(a["H18_pass"]) if key.startswith("H18") else "--"])
    return ("% SAP_v5 hypotheses H16-H18 (exploratory). Generated by tools/site_cal_tables.py.\n\\begin{tabular}{lllll}\n\\toprule\n"
            "quantity & estimate & 95\\,\\% bound or interval & criterion & met \\\\\n\\midrule\n" +
            "\n".join(" & ".join(r) + " \\\\" for r in rows) + "\n\\bottomrule\n\\end{tabular}\n")


def ribcxr(a):
    rib = [("ours", "as is", R / "final" / "rib" / "ours.csv"), ("ours_cal", "site-cal.", R / "site_cal" / "rib_ours_cal.csv"),
           ("qure", "as is", R / "final" / "rib" / "qure.csv"), ("qure_cal", "site-cal.", R / "site_cal" / "rib_qure_cal.csv")]
    rows = [[("ours" if k.startswith("ours") else "reference model") + ", " + lab, f(a["mean_A"][k], 3)] + [f(v, 3) for v in rib_means(p)]
            for k, lab, p in rib]
    return (f"% SAP_v5 H18 run and D2 (exploratory): VinDr-RibCXR, {a['n_sites']} audit sites and 245 images. The as-is absorption of this run\n"
            f"% reproduces the final audit (ours {a['final_mean_A_ours']}, reference {a['final_mean_A_qure']}). Generated by tools/site_cal_tables.py.\n"
            "\\begin{tabular}{lccccc}\n\\toprule\nmethod & mean absorption $A$ & rib-edge reduction & other-lung reduction & selectivity & AUC "
            "\\\\\n\\midrule\n" + "\n".join(" & ".join(r) + " \\\\" for r in rows) + "\n\\bottomrule\n\\end{tabular}\n")


if __name__ == "__main__":
    h = json.loads((R / "site_cal" / "heldout_stats.json").read_text())
    a = json.loads((R / "site_cal" / "audit_stats.json").read_text())
    (T / "site_cal_fidelity.tex").write_text(fidelity(h), encoding="utf-8", newline="\n")
    (T / "site_cal_tests.tex").write_text(tests(h, a), encoding="utf-8", newline="\n")
    (T / "site_cal_ribcxr.tex").write_text(ribcxr(a), encoding="utf-8", newline="\n")
    for n in ("site_cal_fidelity", "site_cal_tests", "site_cal_ribcxr"):
        print((T / f"{n}.tex").read_text(encoding="utf-8"))
