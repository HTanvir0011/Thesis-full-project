"""Condensed, readable versions of the generated result tables for the focused two-study paper -> paper/tables/tmi_*.tex.

python tools/tmi_tables.py
Only rows and columns are selected and method codes are renamed; every numeric cell is copied unchanged, and the script stops if an
output numeric cell does not equal an input cell of the same row (nothing is recomputed). Sources: paper/tables/*.tex written by the
statistics scripts.
"""
import re
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "paper" / "tables"

CODE = {"identity": "Identity", "clahe": "CLAHE", "homomorphic": "Homomorphic filter", "clia_v1": "v1 (LIDC, CLIA)", "recipe_v1": "v1 recipe (LIDC)",
        "qure": "Reference model", "notwin": "No-twin control", "ours": "Ours", "bsldm": "BS-LDM", "swin": "SwinV2-T twin",
        "swin_nt": "SwinV2-T no twin", "rd": "RAD-DINO twin", "rd_nt": "RAD-DINO no twin"}
DATASET = {"nih": "NIH", "node21": "Node21", "tbx": "TBX11K", "vin": "VinBigData", "ribcxr": "VinDr-RibCXR", "jsrt": "JSRT", "szch": "SZCH held-out"}
INPUT = {"orig": "Original", "soft": "Ours (soft)", "soft_qure": "Reference (soft)", "orig+soft": "Original + ours", "orig-soft": "Original + ours",
         "both": "Original + ours + bone", "clahe": "CLAHE"}


def u(s):  # unescape \_
    return s.replace("\\_", "_")


def label(code):
    c = u(code)
    m = re.fullmatch(r"(ours|notwin|swin|swin_nt|rd|rd_nt)_s(\d)", c)
    if m:
        return f"{CODE[m.group(1)]}, seed {m.group(2)}"
    m = re.fullmatch(r"w(\d+)_s(\d)", c)
    if m:
        return f"SwinV2-T twin, $w={m.group(1)}$, seed {m.group(2)}"
    return CODE.get(c, code)


def parse(name):
    t = "\n".join(l for l in (SRC / f"{name}.tex").read_text(encoding="utf-8").splitlines() if not l.lstrip().startswith("%"))
    inner = re.search(r"\\toprule(.*?)\\bottomrule", t, re.S).group(1)
    head, _, rest = inner.partition("\\midrule")
    cells = lambda r: [c.strip() for c in r.split("&")]  # noqa: E731
    return cells(head.replace("\\\\", "")), [cells(r) for r in re.split(r"\\\\\s*", rest) if r.strip()]


def write(name, header, rows, src, comment, spec=None):
    """Write paper/tables/<name>.tex; numeric cells (any cell with a digit that is not in the first two columns) must occur in an input row."""
    src_cells = {c for r in src[1] for c in r}
    for r in rows:
        for c in r[2:]:
            assert c in src_cells or not re.search(r"\d", c), f"{name}: cell {c!r} is not an input cell"
    spec = spec or "l" + "c" * (len(header) - 1)
    body = "\n".join(" & ".join(r) + " \\\\" for r in rows)
    (SRC / f"{name}.tex").write_text(f"% {comment} Generated by tools/tmi_tables.py from {src[2]}.tex.\n\\begin{{tabular}}{{{spec}}}\n\\toprule\n"
                                     + " & ".join(header) + " \\\\\n\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n", encoding="utf-8", newline="\n")
    print("wrote", name, f"({len(rows)} rows)")


def load(name):
    h, rows = parse(name)
    return h, rows, name


def pick(rows, key, order):
    by = {u(r[0]): r for r in rows}
    return [by[k] for k in order]


def main():
    # ---- fidelity on held-out SZCH pairs (Table of the main paper): key methods, six metrics
    h, rows, n = load("szch_heldout")
    over = {"ours": "Ours (twin, $K=3$)", "notwin": "No-twin control ($K=3$)", "qure": "Reference model", "clia_v1": "v1 (LIDC only)",
            "bsldm": "BS-LDM (trained on SZCH pairs)"}
    cols = [0, 1, 2, 3, 4, 6, 9]
    sel = pick(rows, 0, ["identity", "clahe", "homomorphic", "clia_v1", "qure", "notwin", "ours", "bsldm"])
    write("tmi_fidelity", ["method"] + [h[i] for i in cols[1:]], [[over.get(u(r[0]), label(r[0]))] + [r[i] for i in cols[1:]] for r in sel],
          (h, rows, n), "SZCH-X-Rays, 51 held-out pairs.")
    # ---- H2' non-inferiority
    h, rows, n = load("h2_noninferiority")
    mt = {"psnr_cal_bone": "bone PSNR$_{cal}$", "ssim_cal": "SSIM$_{cal}$"}
    write("tmi_h2", ["ours versus", "metric"] + h[2:], [[label(r[0]), mt[u(r[1])]] + r[2:] for r in rows], (h, rows, n),
          "H2' non-inferiority.")
    # ---- ablation of the twin regulariser (header only)
    h, rows, n = load("ablation_twin")
    write("tmi_ablation", [x.replace("QP val MAE", "projection val. MAE") for x in h], rows, (h, rows, n), "Ablation of the twin regulariser.", "l" + "c" * 4)
    # ---- audit contrasts
    h, rows, n = load("audit_contrasts")
    ct = lambda s: s.replace("qure", "reference").replace("notwin", "no-twin")  # noqa: E731
    write("tmi_audit", ["set", "contrast", h[2], h[3], "interaction (overlap $\\geq$15\\% vs $<$15\\%)"],
          [[DATASET[r[0]], ct(r[1])] + r[2:] for r in rows], (h, rows, n), "H3' paired site-level contrasts.")
    # ---- audit means on VinDr-RibCXR: ensembles only (single seeds go to the supplement)
    h, rows, n = load("audit_ribcxr")
    sel = pick(rows, 0, ["identity", "recipe_v1", "clia_v1", "qure", "notwin", "ours", "swin_nt", "swin", "rd_nt", "rd"])
    write("tmi_audit_means", ["method"] + h[1:], [[label(r[0])] + r[1:] for r in sel], (h, rows, n), "Audit means.", "lc")
    # ---- rib benchmark: key methods
    h, rows, n = load("rib_benchmark")
    sel = pick(rows, 0, ["identity", "clahe", "homomorphic", "clia_v1", "qure", "notwin", "ours"])
    write("tmi_rib", ["method"] + h[1:], [[label(r[0])] + r[1:] for r in sel], (h, rows, n), "Rib benchmark on VinDr-RibCXR.")
    # ---- real-nodule contrast
    h, rows, n = load("nodule_cnr")
    nm = lambda s: (s.replace("jsrt", "JSRT").replace("node21", "Node21").replace("(all)", ", all")  # noqa: E731
                    .replace("(bone\\_overlap$\\geq$0.15)", ", bone overlap $\\geq$ 0.15"))
    write("tmi_cnr", [x.replace("Qure", "reference") for x in h], [[nm(r[0])] + r[1:] for r in rows], (h, rows, n), "Real-nodule contrast.")
    # ---- downstream classification and detection
    h, rows, n = load("downstream_cls")
    order = ["orig", "soft", "soft_qure", "orig+soft", "clahe"]
    sel = [next(r for r in rows if u(r[1]) == k) for k in order]
    write("tmi_down_cls", ["dataset", "input"] + [x.replace("vs orig", "vs original") for x in h[2:]], [[DATASET[r[0]], INPUT[u(r[1])]] + r[2:] for r in sel],
          (h, rows, n), "NIH classification.", "ll" + "c" * 3)
    h, rows, n = load("downstream_det")
    order = ["orig", "soft", "soft_qure", "both", "clahe"]
    sel = [next(r for r in rows if r[0] == d and u(r[1]) == k) for d in ("node21", "tbx", "vin") for k in order]
    write("tmi_down_det", ["dataset", "input"] + [x.replace("vs orig", "vs original") for x in h[2:]], [[DATASET[r[0]], INPUT[u(r[1])]] + r[2:] for r in sel],
          (h, rows, n), "Detection.", "ll" + "c" * 5)
    # ---- fusion study (Study II): macro-AUROC per configuration, H6 / H7
    h, rows, n = load("v3_macro")
    cfg = {"orig": "Original", "soft": "Soft", "early": "Early", "hybrid": "Hybrid", "ctrl": "Control"}
    write("tmi_macro", [cfg.get(x, x) for x in h], rows, (h, rows, n), "Seed-ensemble test metrics per configuration.")
    h, rows, n = load("v3_primary")
    rn = lambda s: s.replace(" vs orig", " vs original").replace(" vs ctrl", " vs control")  # noqa: E731
    write("tmi_primary", h, [[r[0], rn(r[1])] + r[2:] for r in rows], (h, rows, n), "H6 and H7.")
    h, rows, n = load("v3_groups")
    rg = lambda s: re.sub(r"-orig$", " $-$ original", s)  # noqa: E731
    write("tmi_groups", h, [[r[0], rg(r[1])] + r[2:] for r in rows], (h, rows, n), "H8 finding groups.")
    # ---- supplement versions with readable method names
    h, rows, n = load("szch_heldout")
    write("tmi_s_szch", h, [[label(r[0])] + r[1:] for r in rows], (h, rows, n), "All methods and seeds.", "l" + "c" * 9)
    h, rows, n = load("audit_ribcxr")
    write("tmi_s_audit_ribcxr", h, [[label(r[0])] + r[1:] for r in rows], (h, rows, n), "All methods and seeds.", "lc")
    h, rows, n = load("rib_benchmark")
    write("tmi_s_rib", h, [[label(r[0])] + r[1:] for r in rows], (h, rows, n), "All methods.")
    h, rows, n = load("encoders")
    en = lambda s: re.sub(r"(\w+) \$-\$ ([\w\\_]+)", lambda m: f"{label(m.group(1))} $-$ {label(m.group(2))}".replace("Ours", "ConvNeXt-V2-T twin")  # noqa: E731
                          .replace("No-twin control", "ConvNeXt-V2-T no twin"), s)
    write("tmi_s_encoders", h, [[DATASET[r[0]], en(r[1])] + r[2:] for r in rows], (h, rows, n), "Twin effect per encoder.")
    h, rows, n = load("bdcxr_cls")
    write("tmi_s_bdcxr_cls", [x.replace("vs orig", "vs original") for x in h], [[INPUT[u(r[0])]] + r[1:] for r in rows], (h, rows, n), "BDCXR-3257 E1.")
    h, rows, n = load("bdcxr_audit")
    write("tmi_s_bdcxr_audit", h, [[label(r[0])] + r[1:] for r in rows], (h, rows, n), "BDCXR-3257 E2.")


if __name__ == "__main__":
    main()
